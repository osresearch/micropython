/*
 * Clock overview:
 * The SAMD/SAML chips have a number of generic clocks (GCLK)
 * each of which can be generated from different inputs,
 * such as internal oscillators, PLLs, external crystals, etc.
 * The GCLK_MAIN is used for the synchronous CPU and the main buses,
 * while each of the GLCKn are used to async clock different peripherals
 * such as.
 *
 * TCn: Timer Counters. These are normally 16-bits, but can be combined
 * in pairs for 32-bit counters. Used for scheduling interrupts, etc.
 * TCCn: Timer Counters for Control: similar to TC, but with extra waveform
 * generation functions for PWM etc
 * RTC: Real time clock
 * 
 *
 * SAML22 has 5 GCLK channels, 4 TC peripherals, 1 TCC.
 * RTC: divided by 1024 => 32 Hz.
 * GCLK0: 8 MHz system clock
 * GCLK1: 48 Mhz USB clock (generated by PLL 32768Hz * 1465
 *
 * TC0: 781 Hz usb device callback
 * TC1: 156 Hz usb cdc callback
 * TC2/3: 32-bit microsecond counter
 */

