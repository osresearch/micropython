static void saml22_us_counter(void)
{
    // is this not required?
    //MCLK->APBCMASK.bit.TC2_ = 1; // Enable TC2 clock
    //MCLK->APBCMASK.bit.TC3_ = 1; // Enable TC3 clock

    hri_gclk_write_PCHCTRL_reg(GCLK, TC2_GCLK_ID, GCLK_PCHCTRL_GEN_GCLK0_Val | GCLK_PCHCTRL_CHEN);
    // and enable the peripheral clock.
    hri_mclk_set_APBCMASK_TC2_bit(MCLK);

    // disable and reset TC2.
    hri_tc_clear_CTRLA_ENABLE_bit(TC2);
    hri_tc_wait_for_sync(TC2, TC_SYNCBUSY_ENABLE);
    hri_tc_write_CTRLA_reg(TC2, TC_CTRLA_SWRST);
    hri_tc_wait_for_sync(TC2, TC_SYNCBUSY_SWRST);
    hri_tc_write_CTRLA_reg(TC2, 0
	| TC_CTRLA_PRESCALER_DIV8 // divide the 8 MHz clock by 8 to count 1 MHz
	| TC_CTRLA_MODE_COUNT32   // count in 32-bit mode (uses TC3 as well)
	| TC_CTRLA_RUNSTDBY       // run in standby, just in case we figure that out
    );
    // set an interrupt on overflow; this will call TC2_Handler below.
    hri_tc_set_INTEN_OVF_bit(TC2);

    // set priority higher than TC1
    NVIC_SetPriority(TC2_IRQn, 5);
    NVIC_ClearPendingIRQ(TC2_IRQn);
    NVIC_EnableIRQ(TC2_IRQn);

    // Start the timer
    hri_tc_set_CTRLA_ENABLE_bit(TC2);
}

