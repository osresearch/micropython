#define LED_RED GPIO(GPIO_PORTA, 21)
#define LED_GREEN GPIO(GPIO_PORTA, 20)
void led_set(int led, int value)
{
    gpio_set_pin_level(led ? LED_RED : LED_GREEN, value);
}
void led_green_toggle()
{
    static int state = 0;
    led_set(1, (state = !state));
}
void led_red_toggle()
{
    static int state = 0;
    led_set(0, (state = !state));
}

void led_init()
{
    gpio_set_pin_direction(LED_RED, GPIO_DIRECTION_OUT);
    gpio_set_pin_direction(LED_GREEN, GPIO_DIRECTION_OUT);
    led_set(0,0);
    led_set(1,0);
}

static void usb_init_saml22(void)
{
    led_init();

    // disable USB, just in case.
    hri_usb_clear_CTRLA_ENABLE_bit(USB);

    // bump clock up to 8 MHz
    hri_oscctrl_write_OSC16MCTRL_FSEL_bf(OSCCTRL, OSCCTRL_OSC16MCTRL_FSEL_8_Val);

    // reset flags and disable DFLL
    OSCCTRL->INTFLAG.reg = OSCCTRL_INTFLAG_DFLLRDY;
    OSCCTRL->DFLLCTRL.reg = 0;
    while (!(OSCCTRL->STATUS.reg & OSCCTRL_STATUS_DFLLRDY));

    // set the coarse and fine values to speed up frequency lock.
    uint32_t coarse =(*((uint32_t *)NVMCTRL_OTP5)) >> 26;
    OSCCTRL->DFLLVAL.reg = 0
	| OSCCTRL_DFLLVAL_COARSE(coarse)
	| OSCCTRL_DFLLVAL_FINE(0x200)
	;

    // set coarse and fine steps, and multiplier (48 MHz = 32768 Hz * 1465)
    OSCCTRL->DFLLMUL.reg = 0
	| OSCCTRL_DFLLMUL_CSTEP( 1 )
	| OSCCTRL_DFLLMUL_FSTEP( 1 )
	//| OSCCTRL_DFLLMUL_MUL( 1465 )
	| OSCCTRL_DFLLMUL_MUL( 48000000 / 32768 + 1 )
	;

    // set closed loop mode, chill cycle disable and USB clock recovery mode, and enable the DFLL.
    OSCCTRL->DFLLCTRL.reg = 0
	| OSCCTRL_DFLLCTRL_MODE
	| OSCCTRL_DFLLCTRL_CCDIS
	| OSCCTRL_DFLLCTRL_ONDEMAND
	| OSCCTRL_DFLLCTRL_RUNSTDBY
	| OSCCTRL_DFLLCTRL_USBCRM
	| OSCCTRL_DFLLCTRL_ENABLE
	;

    while (!(OSCCTRL->STATUS.reg & OSCCTRL_STATUS_DFLLRDY));

    // assign DFLL to GCLK1
    GCLK->GENCTRL[1].reg = 0
	| GCLK_GENCTRL_SRC(GCLK_GENCTRL_SRC_DFLL48M)
	| GCLK_GENCTRL_DIV(1)
	| GCLK_GENCTRL_GENEN
	// | GCLK_GENCTRL_OE
	;

    while (GCLK->SYNCBUSY.bit.GENCTRL1); // wait for generator control 1 to sync

    // assign GCLK1 to USB
    hri_gclk_write_PCHCTRL_reg(GCLK, USB_GCLK_ID, GCLK_PCHCTRL_GEN_GCLK1_Val | GCLK_PCHCTRL_CHEN);
    hri_mclk_set_AHBMASK_USB_bit(MCLK);
    hri_mclk_set_APBBMASK_USB_bit(MCLK);

    // USB Pin Init
    gpio_set_pin_direction(PIN_PA24, GPIO_DIRECTION_OUT);
    gpio_set_pin_level(PIN_PA24, false);
    gpio_set_pin_pull_mode(PIN_PA24, GPIO_PULL_OFF);
    gpio_set_pin_direction(PIN_PA25, GPIO_DIRECTION_OUT);
    gpio_set_pin_level(PIN_PA25, false);
    gpio_set_pin_pull_mode(PIN_PA25, GPIO_PULL_OFF);

    gpio_set_pin_function(PIN_PA24, PINMUX_PA24G_USB_DM);
    gpio_set_pin_function(PIN_PA25, PINMUX_PA25G_USB_DP);

    // the sensor watch enabled usb at this point and scheduled
    // call back timers:
    //_watch_enable_tc0();
    // tusb_init();
    //_watch_enable_tc1();

}


